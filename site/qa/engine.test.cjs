const assert=require('node:assert/strict');
const G=require('../assets/engine.js'), E=require('../episodes/harbor-hall.js');
const send=(s,type,id,value)=>G.step(s,{type,id,value},E);
assert.equal(new Set(E.sources.map(s=>s.id)).size,E.sources.length);
assert.deepEqual(E.claims.map(x=>x.verdict).sort(),['misleading','supported','unresolved']);
assert.deepEqual(E.transfer.items.map(x=>x.verdict).sort(),['misleading','supported','unresolved']);
for (const array of [E.sources,E.claims,E.decisions,E.verdicts,E.transfer.items]) assert(array.every(x=>/^[a-z-]+$/.test(x.id)));
assert.equal(G.compare(E,['post','notice']),'shared');
assert.equal(G.compare(E,['notice','library']),'independent');
for(const x of [[],['post','post'],['post','unknown']]) assert.equal(G.compare(E,x),null);
const fresh=G.create();
for (const type of ['commit','claim','check','repair','pin','decide']) assert.equal(send(fresh,type,'post'),fresh);
let s=send(fresh,'begin'); assert.equal(send(s,'pin','post'),s);
s=send(s,'view','post'); assert.equal(send(s,'trace','notice'),s);
s=send(send(s,'trace','post'),'pin','post');
s=send(send(s,'view','notice'),'pin','notice'); assert.equal(send(s,'compare'),s);
let other=send(s,'view','resident');
assert.equal(send(other,'trace','library'),other,'unopened and unpinned origins stay unavailable');
other=send(other,'trace','notice');
assert.deepEqual(other.traced,['post','notice']);
assert.equal(other.viewed,'resident');
assert.equal(send(other,'trace','notice'),other,'tracing an already known origin leaves the state unchanged');
s=other;
s=send(send(s,'relation','shared'),'compare'); assert.equal(s.compared,true);
s=send(send(s,'view','library'),'pin','library'); assert.deepEqual(s.pair,['notice','library']);
assert.equal(s.compared,false); assert.equal(send(s,'decide'),s);
s=send(send(s,'relation','independent'),'compare'); assert.equal(send(s,'decide'),s);
for(const x of E.claims) s=send(s,'claim',x.id,x.verdict);
assert(G.rows(E.claims,s.claims).every(x=>x.correct));
assert.deepEqual(fresh.claims,{});
let count=0;
for(const d of E.decisions) for(const repair of E.repairs[d.id]) {
  let x=send(s,'decide');assert.equal(x.page,'decide');
  assert.equal(send(x,'commit'),x);
  x=send(x,'choose',d.id);x=send(x,'evidence');assert.equal(x.page,'evidence');assert.deepEqual(x.claims,s.claims);
  x=send(x,'decide');assert.equal(x.decision,d.id);
  x=send(x,'commit');assert.equal(x.page,'review');assert.equal(send(x,'followup','invalid'),x);
  x=send(x,'followup',repair.id);assert.equal(x.page,'debrief');assert.equal(x.repair,repair.id);
  assert.equal(send(x,'check'),x);
  for(const item of E.transfer.items) x=send(x,'transfer',item.id,item.verdict);
  x=send(x,'check');assert.equal(x.checked,true);
  assert.equal(send(x,'transfer',E.transfer.items[0].id,'unresolved'),x);
  assert(G.rows(E.transfer.items,x.transfer).every(x=>x.correct));
  assert.deepEqual(send(x,'reset'),fresh);count++;
}
console.log(count+' publication/recovery paths, state/repair integrity, both provenance types, no bypass, transfer classification and reset passed.');
